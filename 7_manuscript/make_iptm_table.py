#!/usr/bin/env python3
"""Render iptm_ptm_by_complex.csv as a manuscript table.

One row per complex; the eight methods sit under a single spanner, "Best ipTM + pTM".
Control rows are highlighted. Colour never carries the information on its own: the
positive and negative controls are also marked (+) / (-) and set in bold, so the table
survives greyscale printing and colour-blind readers.

Outputs (this folder):
  iptm_ptm_table.tex             booktabs table, \\input-able
  iptm_ptm_table_standalone.tex  wrapper to compile it on its own
  iptm_ptm_table.md              same table in Markdown
"""
from pathlib import Path

import pandas as pd

import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
from controls import POS, NEG, control  # noqa: E402

HERE = Path(__file__).resolve().parent
SRC = HERE / "iptm_ptm_by_complex.csv"

# display name -> name in the CSV, in the column order requested
COLUMNS = [("AFM screen", "AFM_screen"), ("AFM full-DB", "AFM"),
           ("AFM reduced-DB", "AFM_reduced"), ("AF3 Server", "AF3_server"),
           ("AF3 Cluster", "AF3_cluster"), ("AF3 Cluster full-DB", "AF3_fulldb"),
           ("Boltz-2", "Boltz2"), ("Boltz-2 reduced-DB", "Boltz2_reduced")]

PREAMBLE = r"\usepackage{booktabs}  \usepackage[table]{xcolor}"
CAPTION = (
    "Best ipTM + pTM per complex and method. Each value is the highest-scoring of the "
    "five models produced by that method. AFM screen values are the original screen "
    "(\\textit{False\\_positives.xlsx}); AFM full-DB and reduced-DB are the AlphaFold-Multimer "
    "v3 cluster runs with full and reduced databases (top five of 25 predictions by AFM's "
    "own ranking); all other values are the mature-construct runs. AF3 Cluster uses AF3's own MSA search (reduced BFD); AF3 Cluster full-DB is given "
    "the AFM full-database MSAs (BFD + UniRef30). Boltz-2 uses the ColabFold MSA server; "
    "Boltz-2 reduced-DB is given the AF3 pipeline MSAs. Positive controls (+), shaded blue, are interactions demonstrated in the lab; negative controls ($-$), shaded amber, are those that could not be demonstrated (absence of evidence, not proven non-interaction). "
    "P69B\\_Ecp36 is marked \\textsuperscript{a}: the screen run behind its AFM screen value is "
    "not in the repository, and the only Ecp36 run on disk is FLAG-tagged and scores 0.537."
)


def load():
    d = pd.read_csv(SRC)
    order = d.complex.drop_duplicates().tolist()          # keep the CSV's own ordering
    wide = d.pivot(index="complex", columns="method", values="best").loc[order]
    ctrl = d.drop_duplicates("complex").set_index("complex").control.loc[order]
    return wide, ctrl


def tex(wide, ctrl):
    L = [r"% Generated by make_iptm_table.py -- do not edit by hand.",
         rf"% Requires in the preamble: {PREAMBLE}",
         r"\definecolor{ctrlpos}{HTML}{DCE9F5}",
         r"\definecolor{ctrlneg}{HTML}{FBE6D4}",
         "", r"\begin{table}[htbp]", r"\centering\small",
         rf"\caption{{{CAPTION}}}", r"\label{tab:iptmptm}",
         r"\begin{tabular}{@{}l" + "r" * len(COLUMNS) + r"@{}}", r"\toprule",
         r"& \multicolumn{%d}{c}{Best ipTM + pTM} \\" % len(COLUMNS),
         r"\cmidrule(l){2-%d}" % (len(COLUMNS) + 1),
         "Complex & " + " & ".join(n for n, _ in COLUMNS) + r" \\", r"\midrule"]
    for cx in wide.index:
        k = ctrl[cx]
        name = cx.replace("_", r"\_")
        if k == "positive":
            name, shade = rf"\textbf{{{name}}} (+)", r"\rowcolor{ctrlpos}"
        elif k == "negative":
            name, shade = rf"{name} ($-$)", r"\rowcolor{ctrlneg}"
        else:
            shade = ""
        if cx == "P69B_Ecp36":
            name += r"\textsuperscript{a}"
        vals = " & ".join(f"{wide.loc[cx, col]:.3f}" for _, col in COLUMNS)
        L.append(f"{shade}{name} & {vals} " + r"\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(L)


def md(wide, ctrl):
    head = "| Complex | " + " | ".join(f"{n}" for n, _ in COLUMNS) + " |"
    sub = "|:--|" + "--:|" * len(COLUMNS)
    L = [f"**Best ipTM + pTM** (spanning the eight method columns)", "", head, sub]
    for cx in wide.index:
        k = ctrl[cx]
        name = f"**{cx}** (+)" if k == "positive" else f"{cx} (−)" if k == "negative" else cx
        if cx == "P69B_Ecp36":
            name += " ᵃ"
        L.append(f"| {name} | " + " | ".join(f"{wide.loc[cx, c]:.3f}" for _, c in COLUMNS) + " |")
    L += ["", "AFM full-DB and AFM reduced-DB are the AlphaFold-Multimer v3 cluster runs (top five of",
          "25 predictions by AFM's own ranking); AFM screen is the original screen.",
          "AF3 Cluster full-DB is given the AFM full-database MSAs (BFD + UniRef30); Boltz-2",
          "reduced-DB is given the AF3 pipeline MSAs (reduced BFD).",
          "", "Positive controls (+) were demonstrated in the lab; negative controls (−) could not be",
          "demonstrated — absence of evidence, not proven non-interaction.",
          "", "ᵃ The screen run behind P69B_Ecp36's AFM screen value is not in the repository; the only",
          "Ecp36 run on disk is FLAG-tagged and scores 0.537.", ""]
    return "\n".join(L)


def main():
    wide, ctrl = load()
    missing = [c for _, c in COLUMNS if c not in wide.columns]
    if missing:
        raise SystemExit(f"methods absent from {SRC.name}: {missing}")
    (HERE / "iptm_ptm_table.tex").write_text(tex(wide, ctrl))
    (HERE / "iptm_ptm_table.md").write_text(md(wide, ctrl))
    (HERE / "iptm_ptm_table_standalone.tex").write_text(
        "\n".join([r"\documentclass[11pt]{article}",
                   r"\usepackage[a4paper,margin=2cm]{geometry}",
                   r"\usepackage{booktabs}", r"\usepackage[table]{xcolor}",
                   r"\begin{document}", r"\input{iptm_ptm_table.tex}",
                   r"\end{document}", ""]))
    print(wide.rename(columns={c: n for n, c in COLUMNS})[[n for n, _ in COLUMNS]]
          .round(3).to_string())
    print("\ncontrols:", {c: k for c, k in ctrl.items() if k != "unlabelled"})


if __name__ == "__main__":
    main()
